var STORAGE_KEY = "worktic_lang";

function getLang(){
  try{ var v = localStorage.getItem(STORAGE_KEY); if(v==="es"||v==="en") return v; }catch(e){}
  return "es";
}
function setLang(lang){
  try{ localStorage.setItem(STORAGE_KEY, lang); }catch(e){}
  if (typeof window.__wtCurrentView !== 'undefined') {
    // La app principal (app.html) tiene mucho contenido dinámico ya
    // renderizado por app.js; recargar garantiza que TODO (tablas,
    // tarjetas, modales) se vuelva a generar en el nuevo idioma.
    location.reload();
    return;
  }
  applyI18n(lang);
  updateSwitchers(lang);
  document.documentElement.setAttribute("lang", lang);
  window.dispatchEvent(new CustomEvent("worktic:langchange",{detail:{lang:lang}}));
}
function t(key, lang){
  lang = lang || getLang();
  var entry = I18N[key];
  if(!entry) return null;
  return entry[lang] || entry.es || null;
}
function applyI18n(lang){
  lang = lang || getLang();
  var nodes = document.querySelectorAll("[data-i18n]");
  for(var i=0;i<nodes.length;i++){
    var el = nodes[i], key = el.getAttribute("data-i18n"), val = t(key, lang);
    if(val!==null) el.innerHTML = val;
  }
  var ph = document.querySelectorAll("[data-i18n-ph]");
  for(var j=0;j<ph.length;j++){
    var elp = ph[j], keyp = elp.getAttribute("data-i18n-ph"), valp = t(keyp, lang);
    if(valp!==null) elp.setAttribute("placeholder", valp);
  }
}
function updateSwitchers(lang){
  var btns = document.querySelectorAll("[data-lang-switch]");
  for(var i=0;i<btns.length;i++){
    btns[i].textContent = lang==="es" ? "EN" : "ES";
    btns[i].setAttribute("aria-label", lang==="es" ? "Switch to English" : "Cambiar a español");
    btns[i].title = lang==="es" ? "Switch to English" : "Cambiar a español";
  }
}
function bindSwitchers(){
  var btns = document.querySelectorAll("[data-lang-switch]");
  for(var i=0;i<btns.length;i++){
    btns[i].addEventListener("click", function(){
      setLang(getLang()==="es" ? "en" : "es");
    });
  }
}
function wtTitle(view, part){
  // part: 'title' | 'subtitle' — usado por app.js para el encabezado dinámico
  return t((part==="subtitle"?"subtitle.":"title.")+view) || "";
}

window.Worktic_I18N = I18N;
window.wtLang = getLang;
window.wtSetLang = setLang;
window.wtT = t;
window.wtApplyI18n = applyI18n;
window.wtTitle = wtTitle;

document.addEventListener("DOMContentLoaded", function(){
  var lang = getLang();
  document.documentElement.setAttribute("lang", lang);
  applyI18n(lang);
  updateSwitchers(lang);
  bindSwitchers();
});

